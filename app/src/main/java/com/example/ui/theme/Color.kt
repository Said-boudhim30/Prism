fun palettePreviewColor(palette: AccentPalette): Color = when (palette) {
    AccentPalette.LAVENDER -> Color(0xFFD0BCFF)
    AccentPalette.EMERALD -> Color(0xFF6DD58C)
    AccentPalette.OCEAN -> Color(0xFF7CC8FF)
    AccentPalette.AMBER -> Color(0xFFFFB951)
    AccentPalette.ROSE -> Color(0xFFFFAFD2)
    AccentPalette.CORAL -> Color(0xFFFFB4A3)
    AccentPalette.MIDNIGHT -> Color(0xFFA7C7E7)
    AccentPalette.SYSTEM -> Color(0xFFB39DDB)
}

fun getPaletteScheme(palette: AccentPalette, darkTheme: Boolean): ColorScheme = when (palette) {
    AccentPalette.LAVENDER -> if (darkTheme) LavenderDarkScheme else LavenderLightScheme
    AccentPalette.EMERALD -> if (darkTheme) EmeraldDarkScheme else EmeraldLightScheme
    AccentPalette.OCEAN -> if (darkTheme) OceanDarkScheme else OceanLightScheme
    AccentPalette.AMBER -> if (darkTheme) AmberDarkScheme else AmberLightScheme
    AccentPalette.ROSE -> if (darkTheme) RoseDarkScheme else RoseLightScheme
    AccentPalette.CORAL -> if (darkTheme) CoralDarkScheme else CoralLightScheme
    AccentPalette.MIDNIGHT -> if (darkTheme) MidnightDarkScheme else MidnightLightScheme
    AccentPalette.SYSTEM -> if (darkTheme) LavenderDarkScheme else LavenderLightScheme
}
